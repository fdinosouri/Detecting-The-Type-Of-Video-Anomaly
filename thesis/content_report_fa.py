    "This report describes a project on detecting the type of anomaly in "
    "surveillance video. The starting point was the public implementation "
    "of Unbiased Multiple Instance Learning (UMIL), which solves the "
    "problem as a binary decision: a video is either normal or anomalous. "
    "The goal of this project was to extend it to fourteen classes, so "
    "that the model identifies which kind of anomaly occurred rather than "
    "only that one occurred.",

    "The dataset is UCF-Crime: 1900 real surveillance videos across "
    "thirteen anomaly types plus a normal class. Labels exist only at "
    "video level, with no indication of when the event happens in the "
    "training data. This weak supervision places the problem in the "
    "multiple instance learning framework.",

    "Three substantive defects in the evaluation and training paths were "
    "identified and corrected. The architecture was then restructured "
    "around a frozen encoder with cached features, which reduced the cost "
    "of one configuration from roughly sixteen hours to eighty seconds "
    "and made systematic experimentation possible. On that basis, a "
    "transformer head over the temporal axis replaced the per-clip head, "
    "and the encoder was upgraded from ViT-B to ViT-L.",

    "The primary metric is macro-averaged F1 over fourteen classes. It "
    "rose from 0.3049 at the baseline to 0.4298 in the final "
    "configuration, with multiclass accuracy 0.6897 and anomaly-type "
    "accuracy 0.5000. A bootstrap analysis shows that a macro-F1 "
    "difference below roughly 0.075 is indistinguishable from noise on "
    "this test split, and that noise floor is respected throughout the "
    "interpretation of results.",

    "Seven experiments with negative or neutral outcomes are also "
    "reported, including Kinetics-style clip sampling, doubling the "
    "number of clips, and concatenating features from two encoders. "
    "Reporting these is part of the methodological honesty of the work "
    "and marks the real limit of this family of methods.",
